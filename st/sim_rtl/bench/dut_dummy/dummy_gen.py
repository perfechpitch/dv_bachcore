from collections import Counter, namedtuple

IDENT = r"[A-Za-z_][A-Za-z0-9_$]*"
AUTO = "AUTO-GENERATED by dummy_gen.py. DO NOT EDIT."
Signal = namedtuple("Signal", "kind signed packed")
Instance = namedtuple("Instance", "module name parameters ports")
Manual = namedtuple("Manual", "direction packed line")
RtlPort = namedtuple("RtlPort", "direction signal")
RtlInterface = namedtuple("RtlInterface", "parameters ports")


class Error(Exception):
    pass


class Config(object):
    def __init__(self, root, policy, inactive, real, manual, behavior_outputs):
        self.root = root
        self.policy = policy
        self.inactive = inactive
        self.real = real
        self.manual = manual
        self.behavior_outputs = behavior_outputs


class ResolvedPort(object):
    def __init__(self, name, expression):
        self.name = name
        self.expression = expression
        self.direction = None
        self.signal = None
        self.direction_source = None
        self.width_source = None
        self.naming_category = "unresolved"
        self.evidence = []
        self.error = None
        self.notes = []


class ResolvedInstance(object):
    def __init__(self, path, instance, ports, interface_source, parameters):
        self.path = path
        self.instance = instance
        self.ports = ports
        self.interface_source = interface_source
        self.parameters = parameters

    @property
    def conflicts(self):
        return [port for port in self.ports if port.error]

    @property
    def unresolved_direction(self):
        return [port for port in self.ports if port.direction is None and not port.error]

    @property
    def unresolved_width(self):
        return [port for port in self.ports if port.signal is None and not port.error]

    @property
    def status(self):
        if self.conflicts:
            return "ERROR"
        if self.unresolved_direction or self.unresolved_width:
            return "BLOCKED"
        return "READY"


def normalize_manual_width(value):
    if value is None:
        return None
    if re.match(r"^\d+$", value):
        width = int(value)
        if width <= 0:
            raise Error("manual width must be positive: %s" % value)
        return "" if width == 1 else "[%d:0]" % (width - 1)
    if re.match(r"^\[[^\]]+\]$", value):
        return value
    raise Error("invalid manual width '%s'" % value)


def parse_cfg(path):
    root = None
    policy = None
    inactive = []
    real = []
    seen_inactive = set()
    seen_real = set()
    manual = {}
    behavior_outputs = set()
    try:
        lines = path.read_text().splitlines()
    except OSError as exc:
        raise Error("cannot read cfg %s: %s" % (path, exc))
    for number, raw in enumerate(lines, 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split()
        directive = fields[0]
        if directive in ("inactive_all", "real_all"):
            if len(fields) != 1:
                raise Error("%s:%d: %s expects no value" % (path, number, directive))
            if policy is not None:
                raise Error("%s:%d: multiple selection policies: %s and %s" % (path, number, policy, directive))
            policy = directive
        elif directive == "root":
            if len(fields) != 2:
                raise Error("%s:%d: root expects one value" % (path, number))
            if root is not None:
                raise Error("%s:%d: duplicate root" % (path, number))
            if not re.match("^" + IDENT + "$", fields[1]):
                raise Error("%s:%d: invalid root module" % (path, number))
            root = fields[1]
        elif directive == "inactive":
            if len(fields) != 2:
                raise Error("%s:%d: inactive expects one value" % (path, number))
            value = fields[1]
            if not all(re.match("^" + IDENT + "$", item) for item in value.split(".")):
                raise Error("%s:%d: invalid inactive path '%s'" % (path, number, value))
            if value in seen_inactive:
                raise Error("%s:%d: duplicate inactive '%s'" % (path, number, value))
            seen_inactive.add(value)
            inactive.append(value)
        elif directive == "real":
            if len(fields) != 2:
                raise Error("%s:%d: real expects one value" % (path, number))
            value = fields[1]
            if not all(re.match("^" + IDENT + "$", item) for item in value.split(".")):
                raise Error("%s:%d: invalid real path '%s'" % (path, number, value))
            if value in seen_real:
                raise Error("%s:%d: duplicate real '%s'" % (path, number, value))
            seen_real.add(value)
            real.append(value)
        elif directive == "port":
            if len(fields) not in (3, 4):
                raise Error("%s:%d: port expects path.port direction [width]" % (path, number))
            target = fields[1]
            if "." not in target:
                raise Error("%s:%d: port target must include instance path and port" % (path, number))
            instance_path, port_name = target.rsplit(".", 1)
            if not all(re.match("^" + IDENT + "$", item) for item in target.split(".")):
                raise Error("%s:%d: invalid port target '%s'" % (path, number, target))
            direction = fields[2].lower()
            if direction not in ("input", "output"):
                raise Error("%s:%d: invalid direction '%s'" % (path, number, fields[2]))
            key = (instance_path, port_name)
            if key in manual:
                raise Error("%s:%d: duplicate port declaration '%s'" % (path, number, target))
            try:
                packed = normalize_manual_width(fields[3] if len(fields) == 4 else None)
            except Error as exc:
                raise Error("%s:%d: %s" % (path, number, exc))
            manual[key] = Manual(direction, packed, number)
        elif directive == "behavior_output":
            if len(fields) != 2 or "." not in fields[1]:
                raise Error("%s:%d: behavior_output expects instance.port" % (path, number))
            instance_path, port_name = fields[1].rsplit(".", 1)
            if not all(re.match("^" + IDENT + "$", item) for item in fields[1].split(".")):
                raise Error("%s:%d: invalid behavior_output target '%s'" % (path, number, fields[1]))
            key = (instance_path, port_name)
            if key in behavior_outputs:
                raise Error("%s:%d: duplicate behavior_output '%s'" % (path, number, fields[1]))
            behavior_outputs.add(key)
        else:
            raise Error("%s:%d: unknown directive '%s'" % (path, number, directive))
    if root is None:
        raise Error("%s: missing root" % path)
    return Config(root, policy, inactive, real, manual, behavior_outputs)


def apply_selection(config, instances):
    directives = [("inactive", item) for item in config.inactive]
    directives.extend(("real", item) for item in config.real)
    seen = {}
    for state, path in directives:
        if "." in path:
            raise Error("unsupported non-direct-child selection '%s'" % path)
        if path not in instances:
            if state == "inactive":
                raise Error("inactive instance '%s' not found under '%s' (unknown instance)" % (path, config.root))
            raise Error("real instance '%s' not found under '%s' (unknown instance)" % (path, config.root))
        if path in seen:
            raise Error("instance '%s' has conflicting real/inactive selection" % path)
        seen[path] = state
        if config.policy == "inactive_all" and state == "inactive":
            raise Error("redundant inactive selection '%s' with inactive_all" % path)
        if config.policy == "real_all" and state == "real":
            raise Error("redundant real selection '%s' with real_all" % path)
    default = "INACTIVE" if config.policy == "inactive_all" else "REAL"
    selection = dict((name, default) for name in instances)
    for path in config.inactive:
        selection[path] = "INACTIVE"
    for path in config.real:
        selection[path] = "REAL"
    return selection


def strip_comments(text):
    return re.sub(
        r"//[^\n]*|/\*.*?\*/",
        lambda match: "".join("\n" if char == "\n" else " " for char in match.group(0)),
        text,
        flags=re.S,
    )


def matching_close(text, position):
    pairs = {"(": ")", "[": "]", "{": "}"}
    opening = text[position]
    closing = pairs[opening]
    depth = 0
    in_string = False
    escaped = False
    for index in range(position, len(text)):
        char = text[index]
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
        elif char == opening:
            depth += 1
        elif char == closing:
            depth -= 1
            if depth == 0:
                return index
    raise Error("unbalanced %s%s in RTL" % (opening, closing))


def split_top(text):
    result = []
    start = 0
    depths = {"(": 0, "[": 0, "{": 0}
    reverse = {")": "(", "]": "[", "}": "{"}
    for index, char in enumerate(text):
        if char in depths:
            depths[char] += 1
        elif char in reverse:
            depths[reverse[char]] -= 1
        elif char == "," and not any(depths.values()):
            result.append(text[start:index].strip())
            start = index + 1
    result.append(text[start:].strip())
    return [item for item in result if item]


def find_module(text, module_name, source):
    clean = strip_comments(text)
    match = re.search(r"\bmodule\s+%s\b" % re.escape(module_name), clean)
    if not match:
        return None
    position = match.end()
    while position < len(clean) and clean[position].isspace():
        position += 1
    parameter_text = ""
    if position < len(clean) and clean[position] == "#":
        position += 1
        while clean[position].isspace():
            position += 1
        if clean[position] != "(":
            raise Error("%s: unsupported parameter header for module %s" % (source, module_name))
        end = matching_close(clean, position)
        parameter_text = clean[position + 1:end]
        position = end + 1
    while position < len(clean) and clean[position].isspace():
        position += 1
    if position >= len(clean) or clean[position] != "(":
        raise Error("%s: module %s must use an ANSI port header" % (source, module_name))
    port_end = matching_close(clean, position)
    semicolon = clean.find(";", port_end)
    if semicolon < 0:
        raise Error("%s: module %s header is incomplete" % (source, module_name))
    endmodule = re.search(r"\bendmodule\b", clean[semicolon:])
    if not endmodule:
        raise Error("%s: module %s has no endmodule" % (source, module_name))
    body_end = semicolon + endmodule.start()
    return parameter_text, clean[position + 1:port_end], clean[semicolon + 1:body_end]


def declaration_parts(declaration):
    match = re.match(
        r"\s*(?:(input|output|inout)\s+)?(?:(wire|logic|reg)\s+)?(signed\s+)?(\[[^\]]+\]\s*)?(.*)$",
        declaration,
        re.S,
    )
    if not match:
        return None
    return match.group(1), match.group(2), bool(match.group(3)), (match.group(4) or "").strip(), match.group(5)


def add_signals(symbols, declaration):
    parts = declaration_parts(declaration)
    if not parts or not (parts[0] or parts[1]):
        return
    unused_direction, kind, signed, packed, names = parts
    signal = Signal(kind or "wire", signed, packed)
    for item in split_top(names):
        match = re.match(r"^(%s)" % IDENT, item.split("=", 1)[0].strip())
        if match:
            symbols[match.group(1)] = signal


def top_symbols(header, body):
    symbols = {}
    carried = None
    for entry in split_top(header):
        direction = re.match(r"^\s*(input|output|inout)\b", entry)
        if direction:
            carried = direction.group(1)
            add_signals(symbols, entry)
        elif carried:
            add_signals(symbols, carried + " wire " + entry)
    for match in re.finditer(r"(?m)^\s*(?:wire|logic|reg)\b[^;]*;", body):
        add_signals(symbols, match.group(0)[:-1])
    return symbols


def named_connections(text, context):
    result = []
    for entry in split_top(text):
        match = re.match(r"\s*\.(%s)\s*\((.*)\)\s*$" % IDENT, entry, re.S)
        if not match:
            raise Error("ordered or malformed %s is unsupported: %s" % (context, entry))
        result.append((match.group(1), match.group(2).strip()))
    return result


def parse_instances(body):
    ignored = set("assign wire logic reg input output parameter localparam if else for always initial begin end generate".split())
    result = {}
    for match in re.finditer(r"(?m)^\s*(%s)\s*(#\s*\()?" % IDENT, body):
        module_name = match.group(1)
        if module_name in ignored:
            continue
        position = match.end()
        parameters = []
        if match.group(2):
            opening = body.find("(", match.start(), match.end())
            ending = matching_close(body, opening)
            parameters = named_connections(body[opening + 1:ending], "parameter override")
            position = ending + 1
        tail = re.match(r"\s*(%s)\s*\(" % IDENT, body[position:])
        if not tail:
            continue
        name = tail.group(1)
        opening = position + tail.end() - 1
        ending = matching_close(body, opening)
        ports = named_connections(body[opening + 1:ending], "port connection")
        if name in result:
            raise Error("duplicate instance '%s' under root" % name)
        result[name] = Instance(module_name, name, parameters, ports)
    return result


def parse_rtl_ports(header, module_name, source):
    ports = {}
    carried = None
    carried_signal = None
    for entry in split_top(header):
        parts = declaration_parts(entry)
        if parts and parts[0]:
            direction, kind, signed, packed, names = parts
            carried = direction
            carried_signal = Signal(kind or "wire", signed, packed)
        elif carried:
            direction, names = carried, entry
        else:
            raise Error("%s: non-ANSI/directionless port in module %s: %s" % (source, module_name, entry))
        name_match = re.search(r"(%s)\s*$" % IDENT, names.split("=", 1)[0].strip())
        if not name_match:
            raise Error("%s: cannot parse port declaration: %s" % (source, entry))
        name = name_match.group(1)
        if name in ports:
            raise Error("%s: duplicate port %s in module %s" % (source, name, module_name))
        ports[name] = RtlPort(direction, carried_signal)
    return ports


def parse_parameter_declarations(text, source):
    parameters = {}
    for entry in split_top(text):
        entry = re.sub(r"^\s*(?:parameter|localparam)\b", "", entry).strip()
        if not entry:
            continue
        if "=" not in entry:
            raise Error("%s: parameter without default is unsupported: %s" % (source, entry))
        lhs, value = entry.split("=", 1)
        names = re.findall(IDENT, lhs)
        if not names:
            raise Error("%s: cannot parse parameter declaration: %s" % (source, entry))
        parameters[names[-1]] = value.strip()
    return parameters


def parse_module_interfaces(source_paths, module_names):
    found = {}
    for path in source_paths:
        try:
            text = path.read_text()
        except (OSError, UnicodeDecodeError) as exc:
            raise Error("cannot read RTL source %s: %s" % (path, exc))
        for module_name in module_names:
            region = find_module(text, module_name, path)
            if region is None:
                continue
            if module_name in found:
                raise Error("module %s is declared in multiple supplied sources" % module_name)
            parameter_text, header, unused_body = region
            found[module_name] = RtlInterface(
                parse_parameter_declarations(parameter_text, path),
                parse_rtl_ports(header, module_name, path),
            )
    return found


def expand_flist(path, stack=None):
    path = path.resolve()
    stack = list(stack or [])
    if path in stack:
        raise Error("recursive flist include: %s" % path)
    try:
        lines = path.read_text().splitlines()
    except OSError as exc:
        raise Error("cannot read RTL flist %s: %s" % (path, exc))
    result = []
    tokens = []
    for number, raw in enumerate(lines, 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        try:
            tokens.extend((token, number) for token in shlex.split(line, comments=False, posix=True))
        except ValueError as exc:
            raise Error("%s:%d: malformed flist line: %s" % (path, number, exc))
    index = 0
    while index < len(tokens):
        token, number = tokens[index]
        token = os.path.expandvars(token)
        if token == "-f":
            index += 1
            if index >= len(tokens):
                raise Error("%s:%d: -f has no path" % (path, number))
            nested = os.path.expandvars(tokens[index][0])
            result.extend(expand_flist((path.parent / nested), stack + [path]))
        elif token.startswith("-f") and len(token) > 2:
            result.extend(expand_flist(path.parent / token[2:], stack + [path]))
        elif token.startswith("+incdir+"):
            pass
        elif pathlib.Path(token).suffix.lower() in (".v", ".sv"):
            candidate = pathlib.Path(token)
            result.append((candidate if candidate.is_absolute() else path.parent / candidate).resolve())
        else:
            raise Error("%s:%d: unsupported flist token '%s'" % (path, number, token))
        index += 1
    return result


GENERIC = set("u top dummy module block wrapper wrap unit".split())


def block_identities(instance):
    values = set()
    for raw in (instance.name, instance.module):
        raw = re.sub(r"^u_", "", raw.lower())
        words = [word for word in raw.split("_") if word and word not in GENERIC]
        values.update(words)
        for start in range(len(words)):
            for end in range(start + 2, len(words) + 1):
                values.add("".join(words[start:end]))
        if len(words) > 1:
            values.add("".join(word[0] for word in words))
    return values


def endpoint_matches(endpoint, identities):
    if endpoint in identities:
        return True
    if any((len(endpoint) == 1 or len(item) == 1) and (item.startswith(endpoint) or endpoint.startswith(item)) for item in identities):
        return True
    return len(endpoint) <= 3 and any(re.match("^" + ".*".join(map(re.escape, endpoint)), item) for item in identities)


def a2b_evidence(name, identities, source):
    match = re.match(r"^([a-z][a-z0-9]*)2([a-z][a-z0-9]*)(?:_|$)", name.lower())
    if not match:
        return []
    producer, consumer = match.groups()
    producer_match = endpoint_matches(producer, identities)
    consumer_match = endpoint_matches(consumer, identities)
    if producer_match == consumer_match:
        return []
    return [("a2b-%s:%s2%s" % (source, producer, consumer), "output" if producer_match else "input")]


def naming_direction(instance, port_name, expression):
    evidence = []
    lower = port_name.lower()
    if lower.endswith("_i"):
        evidence.append(("suffix:%s" % port_name, "input"))
    if lower.endswith("_o"):
        evidence.append(("suffix:%s" % port_name, "output"))
    identities = block_identities(instance)
    evidence.extend(a2b_evidence(port_name, identities, "port"))
    if re.match("^" + IDENT + "$", expression):
        evidence.extend(a2b_evidence(expression, identities, "connection"))
    directions = set(item[1] for item in evidence)
    suffix = any(item[0].startswith("suffix:") for item in evidence)
    a2b = any(item[0].startswith("a2b-") for item in evidence)
    if len(directions) > 1:
        return None, "naming conflict", evidence
    if not directions:
        return None, "unresolved", evidence
    category = "both rules agreed" if suffix and a2b else "suffix rule resolved" if suffix else "A2B rule resolved"
    return list(directions)[0], category, evidence


def expression_signal(expression, symbols):
    expression = expression.strip()
    constant = re.match(r"^(\d+)\s*'[sS]?[bBoOdDhH][0-9a-fA-F_xXzZ?]+$", expression)
    if constant:
        width = int(constant.group(1))
        return Signal("wire", False, "" if width == 1 else "[%d:0]" % (width - 1))
    if expression.startswith("~"):
        return expression_signal(expression[1:].strip(), symbols)
    if re.match("^" + IDENT + "$", expression):
        if expression not in symbols:
            raise Error("connection signal '%s' has no declaration" % expression)
        return symbols[expression]
    select = re.match(r"^(%s)\[\s*(\d+)\s*(?::\s*(\d+)\s*)?\]$" % IDENT, expression)
    if select:
        name = select.group(1)
        if name not in symbols:
            raise Error("selected signal '%s' has no declaration" % name)
        width = 1 if select.group(3) is None else abs(int(select.group(2)) - int(select.group(3))) + 1
        base = symbols[name]
        return Signal(base.kind, base.signed, "" if width == 1 else "[%d:0]" % (width - 1))
    if expression.startswith("{") and expression.endswith("}"):
        total = 0
        for item in split_top(expression[1:-1]):
            signal = expression_signal(item, symbols)
            if not signal.packed:
                total += 1
                continue
            numeric = re.match(r"^\[\s*(\d+)\s*:\s*(\d+)\s*\]$", signal.packed)
            if not numeric:
                raise Error("concatenation operand has symbolic width: %s" % item)
            total += abs(int(numeric.group(1)) - int(numeric.group(2))) + 1
        return Signal("wire", False, "" if total == 1 else "[%d:0]" % (total - 1))
    if not expression:
        raise Error("empty connection")
    raise Error("unsupported connection expression '%s'" % expression)


def symbolic_names(packed):
    return set(re.findall(IDENT, packed or ""))


def resolved_parameters(instance, ports, parameter_defaults):
    overrides = dict(instance.parameters)
    needed = set()
    for port in ports:
        if port.signal is not None:
            needed.update(symbolic_names(port.signal.packed))
    result = []
    visiting = set()

    def add(name):
        if name in dict(result):
            return
        if name in visiting:
            raise Error("recursive parameter relationship involving %s" % name)
        visiting.add(name)
        if name in overrides:
            # The selected instance supplies the real override during elaboration.
            # A neutral declaration default avoids self-references such as
            # parameter ID_WIDTH = ID_WIDTH.
            value = parameter_defaults.get(name, "0")
        elif name in parameter_defaults:
            value = parameter_defaults[name]
        else:
            raise Error("symbolic width parameter '%s' has no authoritative default/override" % name)
        for dependency in symbolic_names(value):
            if dependency in overrides or dependency in parameter_defaults:
                add(dependency)
        result.append((name, value))
        visiting.remove(name)

    for name in sorted(set(overrides) | needed):
        add(name)
    return result


def resolve_instance(path, instance, symbols, rtl_interface, manual_entries, top_parameter_defaults):
    ports = []
    connected_names = set(name for name, unused in instance.ports)
    rtl_ports = rtl_interface.ports if rtl_interface is not None else None
    if rtl_ports is not None:
        missing = sorted(connected_names - set(rtl_ports))
        if missing:
            raise Error("module %s declaration lacks connected port(s): %s" % (instance.module, ", ".join(missing)))
    for name, expression in instance.ports:
        port = ResolvedPort(name, expression)
        naming, category, evidence = naming_direction(instance, name, expression)
        port.naming_category = category
        port.evidence = evidence
        rtl_port = rtl_ports.get(name) if rtl_ports is not None else None
        if category == "naming conflict":
            port.error = "direction naming conflict"
        if rtl_port is not None:
            port.direction = rtl_port.direction
            port.signal = rtl_port.signal
            port.direction_source = "RTL"
            port.width_source = "RTL"
            if naming is not None and naming != rtl_port.direction:
                port.error = "Naming Convention Conflict: RTL=%s naming=%s" % (rtl_port.direction, naming)
            elif naming is not None:
                port.notes.append("RTL/naming agreed")
        else:
            port.direction = naming
            if naming is not None:
                port.direction_source = "naming"
            try:
                port.signal = expression_signal(expression, symbols)
                port.width_source = "top"
            except Error as exc:
                port.notes.append(str(exc))
        manual = manual_entries.get(name)
        if manual is not None:
            if rtl_port is not None:
                port.error = "redundant manual definition for RTL-resolved port"
            else:
                if port.direction is None:
                    port.direction = manual.direction
                    port.direction_source = "manual"
                elif port.direction != manual.direction:
                    port.error = "manual direction conflict: auto=%s manual=%s" % (port.direction, manual.direction)
                else:
                    port.notes.append("manual direction confirmed")
                if manual.packed is not None:
                    if port.signal is not None:
                        port.error = "redundant manual width; automatic width is already resolved"
                    else:
                        port.signal = Signal("wire", False, manual.packed)
                        port.width_source = "manual"
        ports.append(port)
    unknown_manual = sorted(set(manual_entries) - connected_names)
    if unknown_manual:
        raise Error("manual declaration references unknown port(s) on %s: %s" % (path, ", ".join(unknown_manual)))
    source = "RTL declaration" if rtl_ports is not None else "top inference"
    if any(port.direction_source == "manual" or port.width_source == "manual" for port in ports):
        source += " + manual"
    parameter_defaults = rtl_interface.parameters if rtl_interface is not None else top_parameter_defaults
    try:
        parameters = resolved_parameters(instance, ports, parameter_defaults)
    except Error as exc:
        for port in ports:
            if port.signal is not None and symbolic_names(port.signal.packed):
                port.error = str(exc)
        parameters = []
    return ResolvedInstance(path, instance, ports, source, parameters)


def count_sources(resolved):
    rtl = sum(1 for port in resolved.ports if port.direction_source == "RTL" and port.width_source == "RTL")
    naming = sum(1 for port in resolved.ports if port.direction_source == "naming")
    manual = sum(1 for port in resolved.ports if port.direction_source == "manual" or port.width_source == "manual")
    return rtl, naming, manual


def render_report(config, instances, selection, resolved_instances, verbose=False):
    inactive_count = sum(1 for value in selection.values() if value == "INACTIVE")
    real_count = len(selection) - inactive_count
    ready_count = sum(1 for item in resolved_instances if item.status == "READY")
    blocked_count = inactive_count - ready_count
    setup_ready = blocked_count == 0
    policy = config.policy or "implicit real_all (legacy selective)"
    lines = [
        "# %s" % AUTO, "", "Dummy Setup", "===========", "",
        "Root: %s" % config.root,
        "Selection policy: %s" % policy,
        "", "Direct child instances : %d" % len(instances),
        "Inactive instances     : %d" % inactive_count,
        "Real instances         : %d" % real_count,
        "", "Setup status           : %s" % ("READY" if setup_ready else "BLOCKED"),
        "", "Selection", "=========", "",
        "%-24s %-32s %s" % ("Instance", "Module", "Selection"),
    ]
    for name, instance in instances.items():
        lines.append("%-24s %-32s %s" % (name, instance.module, selection[name]))
    lines.extend(["", "Interface Resolution", "====================", ""])
    for resolved in resolved_instances:
        rtl, naming, manual = count_sources(resolved)
        lines.extend([
            "Instance: %s" % resolved.path,
            "Module: %s" % resolved.instance.module,
            "Status: %s" % resolved.status,
            "Interface source: %s" % resolved.interface_source,
            "",
            "  Total ports          : %d" % len(resolved.ports),
            "  RTL resolved         : %d" % rtl,
            "  Naming resolved      : %d" % naming,
            "  Manual resolved      : %d" % manual,
            "  Unresolved direction : %d" % len(resolved.unresolved_direction),
            "  Unresolved width     : %d" % len(resolved.unresolved_width),
            "  Conflict             : %d" % len(resolved.conflicts),
        ])
        issues = []
        for port in resolved.ports:
            if port.error or port.direction is None or port.signal is None:
                issues.append(port)
        if issues:
            lines.extend(["", "Need confirmation:"])
            for port in issues:
                width = "unresolved" if port.signal is None else port.signal.packed or "1"
                lines.extend([
                    "",
                    "  %s" % port.name,
                    "      direction: %s" % (port.direction or "unresolved"),
                    "      width: %s" % width,
                ])
                reason = port.error or ("; ".join(port.notes) if port.notes else None)
                if reason:
                    lines.append("      reason: %s" % reason)
        if verbose:
            lines.extend(["", "Verbose ports:"])
            for port in resolved.ports:
                width = "unresolved" if port.signal is None else port.signal.packed or "1"
                evidence = "; ".join("%s=%s" % item for item in port.evidence) or "-"
                source = "direction=%s,width=%s" % (port.direction_source or "-", port.width_source or "-")
                lines.append(
                    "  %-36s dir=%-10s width=%-18s category=%-22s source=%-28s connection=%s evidence=%s error=%s"
                    % (port.name, port.direction or "unresolved", width, port.naming_category, source, port.expression or "<empty>", evidence, port.error or "-")
                )
        lines.extend(["", "" ])
    lines.extend(["Summary", "-------", ""])
    for resolved in resolved_instances:
        lines.append("%-12s %-8s unresolved_dir=%-3d unresolved_width=%-3d conflict=%d" % (
            resolved.path, resolved.status, len(resolved.unresolved_direction), len(resolved.unresolved_width), len(resolved.conflicts)))
    lines.extend([
        "", "Direct children : %d" % len(instances),
        "REAL            : %d" % real_count,
        "INACTIVE        : %d" % inactive_count,
        "READY Dummy     : %d" % ready_count,
        "BLOCKED Dummy   : %d" % blocked_count,
        "", "Dummy Setup: %s" % ("READY" if setup_ready else "BLOCKED"),
    ])
    if not setup_ready:
        lines.extend(["", "Manual confirmation required:"])
        for resolved in resolved_instances:
            required = len(set(resolved.unresolved_direction + resolved.unresolved_width + resolved.conflicts))
            if required:
                lines.append("  %-12s: %d" % (resolved.path, required))
    lines.append("")
    return "\n".join(lines)


def render_dummy(resolved, behavior_outputs):
    instance = resolved.instance
    parameter_text = ""
    if resolved.parameters:
        parameter_text = " #(\n" + ",\n".join("  parameter %s = %s" % item for item in resolved.parameters) + "\n)"
    declarations = []
    for port in resolved.ports:
        parts = ["  " + port.direction, "wire"]
        if port.signal.signed:
            parts.append("signed")
        if port.signal.packed:
            parts.append(port.signal.packed)
        parts.append(port.name)
        declarations.append(" ".join(parts))
    lines = ["// %s" % AUTO, "module %s%s (" % (instance.module, parameter_text), ",\n".join(declarations), ");"]
    for port in resolved.ports:
        if port.direction != "output":
            continue
        if (resolved.path, port.name) in behavior_outputs:
            lines.append("  // Driven exclusively by the behavior bind wrapper.")
        else:
            lines.append("  assign %s = '0;" % port.name)
    lines.extend(["endmodule", ""])
    return "\n".join(lines)


def write_outputs(output, config, instances, selection, resolved_instances, verbose):
    output.parent.mkdir(parents=True, exist_ok=True)
    stage = pathlib.Path(tempfile.mkdtemp(prefix=".%s." % output.name, dir=str(output.parent)))
    try:
        (stage / "resolution_report.txt").write_text(render_report(config, instances, selection, resolved_instances, verbose))
        if not all(item.status == "READY" for item in resolved_instances):
            if output.exists():
                shutil.rmtree(str(output))
            stage.replace(output)
            raise Error("Dummy Setup is BLOCKED; see %s" % (output / "resolution_report.txt"))
        modules = {}
        for resolved in resolved_instances:
            content = render_dummy(resolved, config.behavior_outputs)
            previous = modules.get(resolved.instance.module)
            if previous is not None and previous != content:
                raise Error("module %s has incompatible resolved interfaces" % resolved.instance.module)
            modules[resolved.instance.module] = content
        filenames = []
        for module_name, content in sorted(modules.items()):
            filename = module_name + "_inactive_dummy.sv"
            (stage / filename).write_text(content)
            filenames.append(filename)
        config_name = config.root + "_inactive_dummy_cfg"
        config_lines = ["// %s" % AUTO, "config %s;" % config_name, "  design DESIGN_LIB.%s;" % config.root, "  default liblist DESIGN_LIB;"]
        config_lines.extend("  instance %s.%s use DUMMY_LIB.%s;" % (config.root, item.path, item.instance.module) for item in resolved_instances)
        config_lines.extend(["endconfig", ""])
        (stage / "inactive_dummy_config.v").write_text("\n".join(config_lines))
        (stage / "dummy_sources.f").write_text("# %s\n%s\n" % (AUTO, "\n".join(filenames)))
        if output.exists():
            shutil.rmtree(str(output))
        stage.replace(output)
    except Error:
        raise
    except Exception:
        shutil.rmtree(str(stage), ignore_errors=True)
        raise


def run(args):
    config = parse_cfg(args.cfg.resolve())
    try:
        top_text = args.top.resolve().read_text()
    except OSError as exc:
        raise Error("cannot read top %s: %s" % (args.top, exc))
    region = find_module(top_text, config.root, args.top)
    if region is None:
        raise Error("root module '%s' not found in %s" % (config.root, args.top))
    top_parameter_text, top_header, top_body = region
    top_parameter_defaults = parse_parameter_declarations(top_parameter_text, args.top)
    symbols = top_symbols(top_header, top_body)
    instances = parse_instances(top_body)
    selection = apply_selection(config, instances)
    inactive_paths = [name for name in instances if selection[name] == "INACTIVE"]
    for instance_path, unused_port in config.manual:
        if instance_path not in instances:
            raise Error("manual port references unknown/non-inactive instance '%s'" % instance_path)
        if selection[instance_path] == "REAL":
            raise Error("manual Dummy interface configuration targets REAL instance '%s'" % instance_path)
    for instance_path, unused_port in config.behavior_outputs:
        if instance_path not in instances:
            raise Error("behavior_output references unknown instance '%s'" % instance_path)
        if selection[instance_path] == "REAL":
            raise Error("behavior_output targets REAL instance '%s'" % instance_path)
    source_paths = []
    for source in args.rtl_source:
        source_paths.append(source.resolve())
    for flist in args.rtl_flist:
        source_paths.extend(expand_flist(flist))
    unique_sources = []
    seen = set()
    for source in source_paths:
        if source not in seen:
            unique_sources.append(source)
            seen.add(source)
    module_names = set(instances[path].module for path in inactive_paths)
    rtl_interfaces = parse_module_interfaces(unique_sources, module_names)
    resolved = []
    for path in inactive_paths:
        instance = instances[path]
        manual = dict((port_name, value) for (instance_path, port_name), value in config.manual.items() if instance_path == path)
        resolved.append(resolve_instance(path, instance, symbols, rtl_interfaces.get(instance.module), manual, top_parameter_defaults))
    resolved_by_path = dict((item.path, item) for item in resolved)
    for instance_path, port_name in config.behavior_outputs:
        ports = dict((port.name, port) for port in resolved_by_path[instance_path].ports)
        if port_name not in ports:
            raise Error("behavior_output references unknown port '%s.%s'" % (instance_path, port_name))
        if ports[port_name].direction != "output":
            raise Error("behavior_output must reference an output: '%s.%s'" % (instance_path, port_name))
    write_outputs(args.output.resolve(), config, instances, selection, resolved, args.verbose)
    return resolved


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--top", required=True, type=pathlib.Path)
    parser.add_argument("--cfg", required=True, type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path)
    parser.add_argument("--rtl-source", action="append", default=[], type=pathlib.Path, help="authoritative RTL module source; repeatable")
    parser.add_argument("--rtl-flist", action="append", default=[], type=pathlib.Path, help="RTL filelist; repeatable")
    parser.add_argument("--verbose", action="store_true")
    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.output is None:
        args.output = pathlib.Path(__file__).resolve().parent / "generated"
    try:
        resolved = run(args)
    except Error as exc:
        print("dummy_gen.py: error: %s" % exc, file=sys.stderr)
        return 2
    print("generated %d inactive replacement(s) in %s" % (len(resolved), args.output.resolve()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
